def build_farm_art_atlas() -> tuple[Image.Image, dict[str, dict]]:
    """Crop the generated 3x3 art sheet into transparent, frame-addressable sprites."""
    source = Image.open(ART_SOURCE).convert('RGBA')
    art_frames: dict[str, dict] = {}
    names = [
        'orchard-tree', 'farmhouse', 'equipment-barn',
        'gate', 'cattle-group', 'crop-field',
        'silo-water-tower', 'windmill', 'stream-waterfall',
    ]
    atlas = Image.new('RGBA', source.size, (0, 0, 0, 0))
    slot_width, slot_height = source.width // 3, source.height // 3
    for index, name in enumerate(names):
        column, row = index % 3, index // 3
        left, top = column * slot_width, row * slot_height
        right = (column + 1) * slot_width if column < 2 else source.width
        bottom = (row + 1) * slot_height if row < 2 else source.height
        # The generated windmill fan crosses the implied bottom-row cell edge.
        # Extend only that extraction window into the empty strip above it.
        crop_top = max(0, top - 72) if name == 'windmill' else top
        crop = source.crop((left, crop_top, right, bottom))
        alpha = crop.getchannel('A').point(lambda value: 255 if value >= 8 else 0)
        # The generated sheet has occasional disconnected fragments crossing
        # the implied cell boundaries. Keep only each intended object's main
        # component; the cattle and silo/tower slots intentionally contain 3/2.
        raw = alpha.tobytes()
        visited = bytearray(len(raw))
        components: list[list[int]] = []
        width, height = crop.size
        for seed, value in enumerate(raw):
            if not value or visited[seed]:
                continue
            visited[seed] = 1
            stack = [seed]
            component = []
            while stack:
                pixel = stack.pop()
                component.append(pixel)
                x, y = pixel % width, pixel // width
                for ny in range(max(0, y - 1), min(height, y + 2)):
                    row_start = ny * width
                    for nx in range(max(0, x - 1), min(width, x + 2)):
                        neighbor = row_start + nx
                        if raw[neighbor] and not visited[neighbor]:
                            visited[neighbor] = 1
                            stack.append(neighbor)
            components.append(component)
        component_counts = {'cattle-group': 3, 'silo-water-tower': 2}
        intended_count = component_counts.get(name, 1)
        intended = sorted(components, key=len, reverse=True)[:intended_count]
        kept = bytearray(len(raw))
        for component in intended:
            for pixel in component:
                kept[pixel] = 255
        alpha = Image.frombytes('L', crop.size, bytes(kept))
        crop.putalpha(alpha)
        bbox = alpha.getbbox()
        if not bbox:
            raise ValueError(f'Generated art sprite has no visible pixels: {name}')
        padding = 4
        x0, y0, x1, y1 = bbox
        x0, y0 = max(0, x0 - padding), max(0, y0 - padding)
        x1, y1 = min(crop.width, x1 + padding), min(crop.height, y1 + padding)
        sprite = crop.crop((x0, y0, x1, y1))
        # Finish the painterly source as clustered pixel art and soften its
        # saturation to match the natural palette of the terrain tiles.
        color = .62 if name == 'crop-field' else .8
        sprite = ImageEnhance.Color(sprite).enhance(color)
        small = sprite.resize((max(1, sprite.width // 2), max(1, sprite.height // 2)), Image.Resampling.BICUBIC)
        quantized = small.convert('RGB').quantize(colors=48, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert('RGB')
        pixel_art = quantized.resize(sprite.size, Image.Resampling.NEAREST).convert('RGBA')
        pixel_art.putalpha(sprite.getchannel('A').point(lambda value: 255 if value >= 128 else 0))
        sprite = pixel_art
        atlas.alpha_composite(sprite, (left + x0, crop_top + y0))
        anchor = (.5, .92)
        kind = 'generated-decoration'
        if name in {'farmhouse', 'equipment-barn'}:
            kind = 'generated-building'
        elif name in {'crop-field', 'stream-waterfall'}:
            kind = 'generated-ground'
            anchor = (.5, .72)
        elif name == 'cattle-group':
            kind = 'generated-livestock'
        art_frames[f'farm-{name}'] = {
            'frame': {'x': left + x0, 'y': crop_top + y0, 'width': sprite.width, 'height': sprite.height},
            'anchor': {'x': anchor[0], 'y': anchor[1]},
            'kind': kind,
            'worldSize': {'width': 1, 'height': 1},
            'footprint': {'width': 1, 'height': 1},
            'pivot': {'x': anchor[0], 'y': anchor[1], 'space': 'normalized-sprite'},
            'collisionPolygon': [], 'sockets': [], 'clearance': 0.0,
            'atlasKey': 'world-v8-farm-art',
            'reviewStatus': 'REVIEW',
        }
        sprite.save(OUT / f'farm-{name}.png', optimize=True)
    atlas.save(ART_OUTPUT, optimize=True)
    return atlas, art_frames


def build_farm_modules_atlas() -> tuple[Image.Image, dict[str, dict]]:
    source = Image.open(FENCE_SOURCE).convert('RGBA')
    alpha = source.getchannel('A').point(lambda value: 255 if value >= 128 else 0)
    bbox = alpha.getbbox()
    if not bbox:
        raise ValueError('Generated wooden fence module has no visible alpha pixels')
    crop = source.crop(bbox)
    # Pixel-art frames are pre-oriented to the two 2:1 isometric ground axes;
    # runtime sprites stay unrotated around their contact pivots.
    small = crop.resize((256, 128), Image.Resampling.BICUBIC)
    palette = small.convert('RGB').quantize(colors=40, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert('RGB')
    base = palette.resize((512, 256), Image.Resampling.NEAREST).convert('RGBA')
    mask = crop.getchannel('A').resize((512, 256), Image.Resampling.NEAREST).point(lambda value: 255 if value >= 128 else 0)
    base.putalpha(mask)
    rotated = base.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
    old_anchor = (.5 * base.width, .98 * base.height)
    rotated_anchor_px = (base.width - old_anchor[0], old_anchor[1])
    atlas = Image.new('RGBA', (1024, 256), (0, 0, 0, 0))
    atlas.alpha_composite(base, (0, 0))
    atlas.alpha_composite(rotated, (512, 0))
    atlas.save(FENCE_OUTPUT, optimize=True)
    def frame(x: int, image: Image.Image, anchor_px: tuple[float, float]) -> dict:
        anchor = {'x': anchor_px[0] / image.width, 'y': anchor_px[1] / image.height}
        return {
            'frame': {'x': x, 'y': 0, 'width': image.width, 'height': image.height},
            'anchor': anchor, 'kind': 'generated-decoration',
            'worldSize': {'width': 1.5, 'height': .7}, 'footprint': {'width': 1.5, 'height': .7},
            'pivot': {**anchor, 'space': 'normalized-sprite'},
            'collisionPolygon': [[0, 0], [1.5, 0], [1.5, .7], [0, .7]],
            'sockets': [{'id': 'west', 'type': 'fence'}, {'id': 'east', 'type': 'fence'}],
            'clearance': 0, 'atlasKey': 'world-v8-farm-modules', 'reviewStatus': 'REVIEW',
        }
    base_frame = frame(0, base, old_anchor)
    rotated_frame = frame(512, rotated, rotated_anchor_px)
    base.save(OUT / 'farm-fence-wood-segment-y.png', optimize=True)
    rotated.save(OUT / 'farm-fence-wood-segment-x.png', optimize=True)
    return atlas, {
        'farm-fence-wood-segment': dict(base_frame),  # legacy key used by the assembly proof
        'farm-fence-wood-segment-y': base_frame,
        'farm-fence-wood-segment-x': rotated_frame,
    }


def build_stream_modules_atlas() -> tuple[Image.Image, dict[str, dict]]:
    source = Image.open(STREAM_SOURCE).convert('RGBA')
    names = ['stream-straight-east', 'stream-straight-south', 'stream-bend', 'stream-confluence', 'stream-waterfall', 'stream-pond-outlet']
    cell_w, cell_h = source.width // 3, source.height // 2
    atlas = Image.new('RGBA', (cell_w * 3, cell_h * 2), (0, 0, 0, 0))
    frames: dict[str, dict] = {}
    for index, name in enumerate(names):
        col, row = index % 3, index // 3
        crop = source.crop((col * cell_w, row * cell_h, (col + 1) * cell_w, (row + 1) * cell_h))
        # Keep the generated cutout and its edge shadow; remove faint alpha haze
        # from the transparent sheet background, then quantize for crisp pixels.
        alpha = crop.getchannel('A').point(lambda value: 255 if value >= 56 else 0)
        bbox = alpha.getbbox()
        if not bbox:
            raise ValueError(f'Generated stream module has no visible pixels: {name}')
        crop = crop.crop(bbox)
        alpha = alpha.crop(bbox)
        small_size = (max(48, crop.width // 2), max(40, crop.height // 2))
        small = crop.resize(small_size, Image.Resampling.BICUBIC)
        palette = small.convert('RGB').quantize(colors=52, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert('RGB')
        sprite = palette.resize(crop.size, Image.Resampling.NEAREST).convert('RGBA')
        sprite.putalpha(alpha)
        x, y = col * cell_w, row * cell_h
        atlas.alpha_composite(sprite, (x, y))
        frames[name] = {
            'frame': {'x': x, 'y': y, 'width': sprite.width, 'height': sprite.height},
            'anchor': {'x': .5, 'y': .78}, 'kind': 'generated-ground',
            'worldSize': {'width': 1.8, 'height': 1.4}, 'footprint': {'width': 1.8, 'height': 1.4},
            'pivot': {'x': .5, 'y': .78, 'space': 'normalized-sprite'},
            'collisionPolygon': [], 'sockets': [], 'clearance': 0,
            'atlasKey': 'world-v8-water-modules', 'reviewStatus': 'REVIEW',
        }
        sprite.save(OUT / f'{name}.png', optimize=True)
    atlas.save(STREAM_OUTPUT, optimize=True)
    return atlas, frames


def source_tile(path: str) -> Image.Image:
    image = Image.open(ROOT / path).convert('RGBA')
    if image.size == (128, 64):
        return image
    return image.resize((128, 64), Image.Resampling.NEAREST)


def natural_grass_tile(base_grass: Image.Image) -> Image.Image:
    """Extract the top of the curated native pasture sprite as a reusable cell."""
    source = Image.open(ROOT / 'assets/candidates/environment/pasture-grass-native-imagegen-v1.png').convert('RGBA')
    # The original is a raised ground chunk. Keep only its grassy top so the
    # world model can continue to draw height and cliff faces independently.
    top = source.crop((0, 0, source.width, round(source.height * .54)))
    mask = Image.new('L', top.size, 0)
    ImageDraw.Draw(mask).polygon([
        (top.width / 2, 0), (top.width - 1, top.height * .48),
        (top.width / 2, top.height - 1), (0, top.height * .48),
    ], fill=255)
    alpha = top.getchannel('A').point(lambda value: 255 if value >= 128 else 0)
    top.putalpha(ImageChops.multiply(alpha, mask))
    small = top.resize((128, 64), Image.Resampling.LANCZOS)
    reduced = small.convert('RGB').quantize(colors=28, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert('RGB')
    texture = reduced.convert('RGBA')
    texture.putalpha(small.getchannel('A').point(lambda value: 255 if value >= 128 else 0))
    result = base_grass.copy()
    result.alpha_composite(texture)
    return result


def water_tile(phase: int, connected_edges: int = 15) -> Image.Image:
    # The muted blue palette is sampled from the curated local pond sprite.
    source = Image.open(ROOT / 'docs/assets/kit-base-v1/water/pond-small-01.png').convert('RGBA')
    pixels = [pixel[:3] for pixel in source.getdata() if pixel[2] > pixel[0] * 1.18 and pixel[2] > pixel[1] * 1.05 and pixel[2] > 70]
    palette_image = Image.new('RGB', (len(pixels), 1))
    palette_image.putdata(pixels)
    palette = palette_image.quantize(colors=6, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert('RGB')
    blues = sorted(set(palette.getdata()), key=lambda rgb: (rgb[2] - rgb[0], rgb[2]), reverse=True)
    mid = blues[min(3, len(blues) - 1)]
    light = blues[min(5, len(blues) - 1)]
    tile = Image.new('RGBA', (128, 64), (0, 0, 0, 0))
    diamond = [(64, -2), (130, 32), (64, 66), (-2, 32)]
    draw = ImageDraw.Draw(tile)
    draw.polygon(diamond, fill=mid)
    # Broad, stepped highlights stay on a stable 2 px pixel grid.
    shifts = [(18, 0), (42, 5), (71, 2)][phase % 3]
    draw.rectangle((30 + shifts[0], 27 + shifts[1], 42 + shifts[0], 29 + shifts[1]), fill=light)
    draw.rectangle((42 + shifts[0], 29 + shifts[1], 48 + shifts[0], 31 + shifts[1]), fill=light)
    draw.rectangle((77 - shifts[1], 39 - shifts[1], 87 - shifts[1], 41 - shifts[1]), fill=light)
    draw.rectangle((88 - shifts[1], 41 - shifts[1], 92 - shifts[1], 43 - shifts[1]), fill=light)
    # Exposed cardinal edges receive their own low pixel-art bank. The mask
    # matches the cell graph, so adjoining water stays blue while shorelines
    # follow bends and narrow channels instead of exposing a full blue diamond.
    edges = [
        ((128, 32), (64, 64), (-.894, -.447)),
        ((0, 32), (64, 64), (.894, -.447)),
        ((64, 0), (0, 32), (.894, .447)),
        ((64, 0), (128, 32), (-.894, .447)),
    ]
    for edge_index, (start, end, inward) in enumerate(edges):
        if connected_edges & (1 << edge_index):
            continue
        dx, dy = end[0] - start[0], end[1] - start[1]
        outer = [(start[0] + dx * step / 8, start[1] + dy * step / 8) for step in range(9)]
        depths = [7 + ((step * 7 + phase * 3 + edge_index * 5) % 6) for step in range(9)]
        inner = [(point[0] + inward[0] * depth, point[1] + inward[1] * depth) for point, depth in zip(outer, depths)]
        draw.polygon(outer + inner[::-1], fill=(105, 119, 78))
        shore = [(point[0] + inward[0] * (depth * .48), point[1] + inward[1] * (depth * .48)) for point, depth in zip(outer, depths)]
        draw.line(shore, fill=(104, 77, 52), width=3)
        foam = [(point[0] + inward[0] * (depth + 2), point[1] + inward[1] * (depth + 2)) for point, depth in zip(outer, depths)]
        draw.line(foam, fill=(157, 190, 165), width=2)
        for step in (1, 4, 7):
            point = inner[step]
            rock_color = ((135, 129, 99) if (step + edge_index) % 2 else (83, 96, 77))
            draw.rectangle((round(point[0] - 2), round(point[1] - 1), round(point[0] + 2), round(point[1] + 1)), fill=rock_color)
    # Hard alpha on the iso boundary avoids soft halos in nearest-neighbour rendering.
    mask = Image.new('L', tile.size, 0)
    ImageDraw.Draw(mask).polygon(diamond, fill=255)
    tile.putalpha(mask)
    return tile


def cliff_face(variant: int, direction: str) -> Image.Image:
    # AI source atlas: two matching cutaway orientations. Normalize with nearest
    # sampling to the engine's 80×72 world-edge cell so pixel scale stays crisp.
    if CLIFF_MODULE_SOURCE.exists():
        source = Image.open(CLIFF_MODULE_SOURCE).convert('RGBA')
        bounds = (110, 67, 776, 649) if direction == 'east' else (923, 95, 1319, 583)
        return source.crop(bounds).resize((80, 72), Image.Resampling.NEAREST)
    image = Image.new('RGBA', (80, 72), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    palette = [(96, 64, 48), (112, 73, 51), (130, 85, 57), (77, 57, 45), (148, 101, 66), (102, 77, 55)]
    # In the 2:1 projection, the +x edge slopes up-right and the +y edge
    # slopes down-right. Keep the face art aligned with the shared tile edge.
    polygon = ([(8, 32), (72, 0), (72, 40), (8, 72)] if direction == 'east'
               else [(8, 0), (72, 32), (72, 72), (8, 40)])
    draw.polygon(polygon, fill=palette[variant % len(palette)])
    rng = random.Random(8800 + variant)
    for _ in range(24):
        x, y = rng.randrange(10, 68, 2), rng.randrange(4, 68, 2)
        w, h = rng.choice((2, 4, 6)), rng.choice((2, 2, 4))
        draw.rectangle((x, y, min(70, x + w), min(70, y + h)), fill=palette[rng.randrange(len(palette))])
    for x, y in [(13, 12), (23, 45), (41, 23), (54, 56)]:
        draw.line((x, y, x + 3, y + 1, x + 5, y + 1), fill=palette[(variant + 3) % len(palette)], width=2)
    for x, y in [(13, 34), (34, 8), (49, 50)]:
        draw.line((x, y, x + 4, y), fill=palette[(variant + 4) % len(palette)], width=2)
    draw.line([polygon[0], polygon[1]], fill=(67, 57, 43), width=2)
    face_mask = Image.new('L', image.size, 0)
    ImageDraw.Draw(face_mask).polygon(polygon, fill=255)
    image.putalpha(ImageChops.multiply(image.getchannel('A'), face_mask))
    return image


def imagegen_cow_frame(index: int) -> Image.Image:
    global _COW_WALK_FRAMES
    if _COW_WALK_FRAMES is None:
        sheet = Image.open(COW_WALK_SOURCE).convert('RGBA')
        channels = sheet.split()
        red_noise = ImageChops.multiply(
            channels[3],
            ImageChops.multiply(
                channels[0].point(lambda v: 255 if v > 145 else 0),
                ImageChops.multiply(channels[1].point(lambda v: 0 if v > 90 else 255),
                                    channels[2].point(lambda v: 0 if v > 105 else 255))))
        alpha = ImageChops.subtract(channels[3], red_noise)
        sheet.putalpha(alpha)
        _COW_WALK_FRAMES = []
        frame_width = sheet.width // 4
        for frame_index in range(4):
            cell = sheet.crop((frame_index * frame_width, 0, (frame_index + 1) * frame_width, sheet.height))
            bbox = cell.getchannel('A').getbbox()
            subject = cell.crop(bbox)
            subject.thumbnail((112, 80), Image.Resampling.NEAREST)
            frame = Image.new('RGBA', (128, 96), (0, 0, 0, 0))
            frame.alpha_composite(subject, ((128 - subject.width) // 2, 96 - subject.height))
            _COW_WALK_FRAMES.append(frame)
    return _COW_WALK_FRAMES[index % 4]


def bridge_sprite() -> Image.Image:
    image = Image.new('RGBA', (192, 112), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    # Contact shadow, two abutments, deck, planks and rails form one reusable cutout.
    draw.polygon([(26, 67), (107, 32), (169, 52), (85, 91)], fill=(31, 48, 44, 92))
    draw.polygon([(30, 62), (43, 56), (49, 71), (35, 77)], fill=(97, 74, 48))
    draw.polygon([(150, 41), (163, 36), (170, 51), (156, 57)], fill=(97, 74, 48))
    deck = [(28, 55), (108, 20), (166, 42), (84, 81)]
    draw.polygon(deck, fill=(154, 105, 61))
    draw.line([deck[0], deck[1], deck[2]], fill=(209, 158, 96), width=3)
    draw.line([deck[0], deck[3], deck[2]], fill=(75, 55, 38), width=3)
    # Cross planks and pixel grain follow the bridge deck's two isometric axes.
    for index in range(1, 8):
        t = index / 8
        x1, y1 = round(28 + (108 - 28) * t), round(55 + (20 - 55) * t)
        x2, y2 = round(84 + (166 - 84) * t), round(81 + (42 - 81) * t)
        draw.line((x1, y1, x2, y2), fill=(113, 76, 48), width=2)
    for (x, y) in [(34, 51), (105, 19), (161, 41), (88, 77)]:
        draw.rectangle((x - 3, y - 7, x + 2, y + 9), fill=(75, 55, 38))
        draw.rectangle((x - 2, y - 8, x + 3, y + 5), fill=(179, 126, 73))
    draw.line((34, 46, 107, 11, 161, 34), fill=(93, 62, 41), width=4)
    draw.line((40, 54, 110, 23, 155, 42), fill=(224, 176, 111), width=3)
    draw.line((40, 54, 110, 23, 155, 42), fill=(103, 69, 43), width=1)
    draw.line((88, 75, 154, 45), fill=(103, 69, 43), width=3)
    return image


def stylized_tree() -> Image.Image:
    source = Image.open(ROOT / 'assets/approved/vegetation/shade-tree-v2.png').convert('RGBA')
    alpha = source.getchannel('A')
    bbox = alpha.getbbox()
    cropped = source.crop(bbox) if bbox else source
    small = pixelize(cropped, (72, 80), 22)
    silhouette = small.getchannel('A')
    outline = Image.new('RGBA', small.size, (43, 57, 43, 0))
    outline.putalpha(silhouette.filter(ImageFilter.MaxFilter(3)))
    outline.alpha_composite(small)
    return outline.resize((144, 160), Image.Resampling.NEAREST)


def stylized_cow_frame(state: str, index: int) -> Image.Image:
    source_path = ROOT / 'assets/candidates/livestock/animation-v1/nelore-state-atlas-v1.png'
    metadata_path = ROOT / 'assets/candidates/livestock/animation-v1/nelore-state-atlas-v1.json'
    source = Image.open(source_path).convert('RGBA')
    metadata = json.loads(metadata_path.read_text())['clips'][state]['frames'][index]
    frame = source.crop((metadata['x'], metadata['y'], metadata['x'] + metadata['width'], metadata['y'] + metadata['height']))
    alpha = frame.getchannel('A')
    bbox = alpha.getbbox()
    if bbox:
        frame = frame.crop(bbox)
    pixels = frame.load()
    for y in range(frame.height):
        for x in range(frame.width):
            red, green, blue, opacity = pixels[x, y]
            # The source atlas has bright yellow keying fringes around some
            # review frames; neutralize those edge pixels before palette work.
            if opacity and red > 180 and green > 135 and blue < 120 and red - blue > 90:
                pixels[x, y] = (226, 215, 190, opacity)
    return pixelize(frame, (64, 48), 18).resize((128, 96), Image.Resampling.NEAREST)


