import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {createServer} from '../../src/server/server.js';
import {chromium} from 'playwright';

const server=createServer({env:{}});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const root=`http://127.0.0.1:${server.address().port}`;
const evidence='docs/evidence/visual-review/2026-10-15';
mkdirSync(evidence,{recursive:true});
let browser;
try{
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const page=await context.newPage();
  await page.addInitScript(()=>{
    const postMessage=Worker.prototype.postMessage;
    Worker.prototype.postMessage=function(message,...args){
      if(message?.type==='populationCompare'){
        setTimeout(()=>postMessage.call(this,message,...args),300);
        return;
      }
      return postMessage.call(this,message,...args);
    };
  });
  const errors=[];
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`${root}/product.html`,{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('.site-header').evaluate(node=>node.getBoundingClientRect().height),64,'desktop header band should retain its compact height');
  assert.equal(await page.locator('.header-wordmark').evaluate(node=>getComputedStyle(node).fontSize),'24.7px','desktop wordmark should be enlarged by 30%');
  assert.equal(await page.locator('.header-manifesto').evaluate(node=>getComputedStyle(node).fontSize),'14.3px','desktop navigation text should be enlarged by 30%');
  assert.equal(await page.evaluate(()=>document.querySelector('.site-header').getBoundingClientRect().bottom<=document.querySelector('.welcome h1').getBoundingClientRect().top),true,'desktop Product content should clear the fixed header');
  for(const width of [640,390,320]){
    await page.setViewportSize({width,height:900});
    const layout=await page.evaluate(()=>{const rect=selector=>{const r=document.querySelector(selector).getBoundingClientRect();return {left:r.left,right:r.right}};return {viewport:innerWidth,document:document.documentElement.scrollWidth,left:rect('.header-manifesto'),brand:rect('.header-mark-group'),utilities:rect('.header-utilities'),buttonVisible:document.querySelector('.theme-toggle').getBoundingClientRect().width>0}});
    assert.equal(layout.document,layout.viewport,`header should not cause mobile overflow at ${width}px`);
    assert.equal(layout.left.right<=layout.brand.left&&layout.brand.right<=layout.utilities.left,true,`header groups should not overlap at ${width}px`);
    assert.equal(layout.buttonVisible,true,`theme control should remain available at ${width}px`);
  }
  await page.setViewportSize({width:1440,height:1100});
  assert.equal(await page.locator('#analysis-area').isVisible(),false,'initial state must not show uncomputed analysis');
  await page.screenshot({path:`${evidence}/01-product-empty.png`,fullPage:true});
  const prompt='Compare a pasture herd of 200 Nelore cattle over 30 days in hot weather, changing supplementation from 0.5 to 1.5 kg DM per animal per day.';
  await page.locator('#prompt-input').fill(prompt);
  await page.locator('#prompt-form button[type="submit"]').click();
  await page.locator('.spec-card .primary-button').waitFor();
  assert.equal(await page.locator('#live-status').innerText(),'','interpreting status must clear once review is ready');
  assert.equal(await page.locator('.population-empty').isVisible(),true,'review should show a clear no-results state');
  assert.equal(await page.locator('.population-grid').isVisible(),false,'review must not show an empty results grid');
  const review=await page.locator('.spec-card').innerText();
  assert.match(review,/200 animals/);
  await page.locator('.review-details summary').click();
  const fullReview=await page.locator('.spec-card').innerText();
  assert.match(fullReview,/Nelore · prompt metadata only/);
  assert.match(review,/No AI provider is configured/);
  assert.equal(await page.locator('.animal-cell').count(),0,'review must not execute');
  await page.locator('.review-details summary').click();
  await page.screenshot({path:`${evidence}/02-product-review.png`,fullPage:true});
  await page.locator('.spec-card .primary-button').click();
  await page.waitForFunction(()=>document.querySelector('#followup-input').disabled);
  assert.equal(await page.locator('#followup-form button').isDisabled(),true,'follow-up must be disabled during a Worker run');
  await page.locator('#followup-input').evaluate(input=>{input.value='make it 15 days';input.form.requestSubmit();});
  assert.match(await page.locator('.spec-card').innerText(),/30 days/,'in-flight follow-up must not replace the specification for the running result');
  await page.waitForFunction(()=>document.querySelectorAll('.animal-cell').length===200);
  assert.equal(await page.locator('#analysis-area').isVisible(),true);
  assert.equal(await page.locator('.spec-card .primary-button').count(),0,'completed review must not still offer the same run action');
  assert.match(await page.locator('.review-state').innerText(),/Comparison complete/);
  assert.match(await page.locator('#workspace-meta').innerText(),/200 animals · 30 days/);
  assert.match(await page.locator('#legend-low-label').innerText(),/kg/);
  await page.screenshot({path:`${evidence}/03-product-results.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),true,'mobile results workspace must not overflow horizontally');
  await page.locator('.conversation').evaluate(el=>{el.scrollTop=el.scrollHeight;});
  await page.waitForFunction(()=>document.querySelector('#live-status').textContent==='');
  await page.screenshot({path:`${evidence}/04-product-workspace-mobile.png`,fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  await page.locator('.animal-cell').nth(1).click();
  assert.match(await page.locator('#animal-inspector').innerText(),/Animal 2/);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export-json').click();
  assert.equal((await downloadPromise).suggestedFilename(),'riose-population-comparison.json');
  await page.locator('#timeline').evaluate(input=>{input.value=String(Number(input.max)-1);input.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.locator('#followup-input').fill('make it 15 days');
  await page.locator('#followup-form button').click();
  assert.equal(await page.locator('#analysis-area').isVisible(),false,'revision clears stale analysis and does not auto-run');
  assert.match(await page.locator('.spec-card').innerText(),/15 days/);
  assert.equal(await page.locator('.spec-card .primary-button').isVisible(),true,'a revised draft requires a fresh explicit run confirmation');
  await page.locator('.spec-card .primary-button').click();
  await page.waitForFunction(()=>document.querySelectorAll('.animal-cell').length===200);
  assert.match(await page.locator('#workspace-meta').innerText(),/200 animals · 15 days/);
  await page.locator('.back-link').click();
  await page.locator('.history-row').first().click();
  await page.getByText(/Replayed with the same manifest snapshot and seed/).waitFor();
  assert.match(await page.locator('#workspace-meta').innerText(),/200 animals · 15 days/);
  await page.setViewportSize({width:1440,height:1100});
  const retiredExperiments=await page.request.get(`${root}/experiments.html`,{maxRedirects:0});
  assert.equal(retiredExperiments.status(),308,'retired Experiments page should redirect');
  assert.equal(retiredExperiments.headers().location,'/product.html','retired Experiments page should lead to Product');
  await page.goto(`${root}/experiments.html`,{waitUntil:'domcontentloaded'});
  assert.match(page.url(),/\/product\.html$/,'legacy Experiments URL should resolve to Product');
  assert.equal(await page.getByRole('heading',{name:'What would happen if?',exact:true}).count(),1,'retired route should open the Product experience');
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${root}/product.html`,{waitUntil:'domcontentloaded'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile page must not overflow horizontally');
  assert.equal(await page.locator('.site-header').evaluate(node=>node.getBoundingClientRect().height),60,'mobile header band should retain its compact height');
  assert.equal(await page.locator('.header-wordmark').evaluate(node=>getComputedStyle(node).fontSize),'20.8px','mobile wordmark should be enlarged by 30%');
  assert.equal(await page.evaluate(()=>document.querySelector('.welcome .eyebrow').getBoundingClientRect().top>=document.querySelector('.site-header').getBoundingClientRect().bottom),true,'mobile Product content should clear the fixed header');
  await page.screenshot({path:`${evidence}/05-product-empty-mobile.png`,fullPage:true});
  await page.goto(`${root}/home.html`,{waitUntil:'domcontentloaded'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),true,'mobile home should not overflow horizontally');
  assert.equal(await page.locator('.hero-monogram').innerText(),'®','hero should use the registered Riose mark');
  await page.locator('.theme-toggle').click();
  assert.match(await page.locator('.hero-wordmark').evaluate(node=>getComputedStyle(node).color),/rgb\(238, 239, 233\)/,'dark mode should keep the home wordmark legible');
  await page.locator('.theme-toggle').click();
  assert.equal(await page.locator('.experiment-preview-map img').evaluate(img=>img.complete&&img.naturalWidth>0),true,'population preview map should load');
  assert.equal(await page.locator('a').evaluateAll(links=>links.some(link=>link.textContent.trim().toLowerCase()==='data')),false,'home header should not expose the retired Data tab');
  await page.setViewportSize({width:768,height:1024});
  const tabletLayout=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth,gap:(()=>{const title=document.querySelector('.hero-lockup').getBoundingClientRect();const cow=document.querySelector('.hero-scene').getBoundingClientRect();return cow.top+35-title.bottom})()}));
  assert.equal(tabletLayout.width,tabletLayout.viewport,'tablet home should not overflow horizontally');
  assert.ok(tabletLayout.gap<130,'tablet portrait should keep the brand and cattle scene visually connected');
  await page.setViewportSize({width:1680,height:944});
  assert.equal(await page.locator('.hero-scene img').evaluate(img=>img.complete&&img.naturalWidth>0),true,'historical cow illustration should load');
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${root}/manifesto.html`,{waitUntil:'domcontentloaded'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),true,'mobile manifesto should not overflow horizontally');
  assert.equal(await page.evaluate(()=>document.querySelector('.site-header').getBoundingClientRect().bottom<=document.querySelector('.manifesto-copy h1').getBoundingClientRect().top),true,'mobile manifesto title should clear the fixed header');
  assert.equal(await page.locator('.farm-scene').evaluate(img=>img.complete&&img.naturalWidth>0),true,'manifesto pixel-art farm should load');
  assert.equal(await page.locator('.cow-sprite').count(),5,'farm should expose five individually focusable decorative cattle sprites');
  assert.equal(await page.locator('.cow-sprite img').evaluateAll(images=>images.every(img=>img.complete&&img.naturalWidth>0)),true,'both sprite frames should load');
  assert.equal(await page.locator('.header-manifesto').getAttribute('aria-current'),'page','manifesto navigation should identify the current page');
  await page.locator('.manifesto-farm').scrollIntoViewIfNeeded();
  await page.locator('.manifesto-farm.is-visible').waitFor();
  await page.screenshot({path:`${evidence}/06-manifesto-mobile.png`});
  await page.setViewportSize({width:1440,height:1050});
  await page.goto(`${root}/manifesto.html`,{waitUntil:'domcontentloaded'});
  assert.equal(await page.evaluate(()=>document.querySelector('.site-header').getBoundingClientRect().bottom<=document.querySelector('.manifesto-copy h1').getBoundingClientRect().top),true,'desktop manifesto title should clear the fixed header');
  await page.locator('.manifesto-farm').scrollIntoViewIfNeeded();
  await page.locator('.manifesto-farm.is-visible').waitFor();
  await page.screenshot({path:`${evidence}/07-manifesto-desktop.png`});
  const cow=page.locator('.cow-sprite').first(),graze=cow.locator('.cow-graze');
  await cow.hover();
  assert.equal(await graze.evaluate(node=>getComputedStyle(node).animationName),'cow-graze-peek','hover should trigger only the short grazing pose change');
  assert.ok(Number(await graze.evaluate(node=>getComputedStyle(node).opacity))>.9,'the grazing pose should appear immediately on hover');
  assert.ok(Number(await cow.locator('img').first().evaluate(node=>getComputedStyle(node).opacity))<.1,'sprite frames must cross-fade by pose visibility, not overlap two cow heads');
  await page.screenshot({path:`${evidence}/08-manifesto-cow-hover.png`});
  await cow.focus();
  assert.equal(await graze.evaluate(node=>getComputedStyle(node).animationName),'cow-graze-peek','keyboard focus should trigger the same interaction');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await graze.evaluate(node=>getComputedStyle(node).animationName),'none','reduced-motion preference should disable the pose animation');
  await page.emulateMedia({reducedMotion:'no-preference'});
  const themeToggle=page.locator('.theme-toggle');
  await themeToggle.click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark','theme switch should activate dark mode');
  assert.equal(await themeToggle.getAttribute('aria-pressed'),'true','dark mode should be exposed to assistive technology');
  assert.equal(await themeToggle.innerText(),'light','dark mode control should offer the light mode action');
  assert.match(await page.locator('body').evaluate(node=>getComputedStyle(node).backgroundColor),/rgb\(23, 25, 22\)/,'dark mode should change the page surface, not only the toggle label');
  assert.match(await page.locator('html').evaluate(node=>getComputedStyle(node).backgroundColor),/rgb\(23, 25, 22\)/,'dark mode should cover the full document canvas');
  await page.reload({waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark','selected theme should persist across navigation');
  await page.locator('.theme-toggle').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light','user should be able to return to the light theme');
  assert.deepEqual(errors,[],'browser console should be free of errors');
  console.log('Product E2E PASS: prompt → review → explicit paired run → 200 animal grid → inspection/export → revision/re-run → local replay; home and manifesto responsive assets/header checks pass.');
}finally{
  await browser?.close();
  await new Promise(resolve=>server.close(resolve));
}
